/** Fail fast in dev if two pairs share an id (pickFresh would treat them as the same pair) */
{
  const seen = new Set<string>();
  for (const p of SPY_PAIRS) {
    if (seen.has(p.id)) throw new Error(`Duplicate spy pair id: ${p.id}`);
    seen.add(p.id);
  }
}
